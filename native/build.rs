// M1: embed ALL of assets/minecraft/worldgen/** into the binary.
// Walks the assets dir at compile time and emits a static manifest of
// (virtual path, include_bytes!) pairs. Runtime loads from memory only.

use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR").unwrap();
    let assets_root = Path::new(&manifest_dir).join("assets");
    let mut entries: Vec<(String, PathBuf)> = Vec::new();
    walk(&assets_root, &assets_root, &mut entries);
    entries.sort();

    let mut out = String::from("// generated by build.rs — do not edit\n");
    out.push_str("pub static ASSET_PATHS: &[&str] = &[\n");
    for (name, _) in &entries {
        out.push_str(&format!("    {:?},\n", name));
    }
    out.push_str("];\n\npub static ASSET_BYTES: &[&[u8]] = &[\n");
    for (_, path) in &entries {
        out.push_str(&format!("    include_bytes!({:?}),\n", path));
    }
    out.push_str("];\n");

    let out_dir = std::env::var("OUT_DIR").unwrap();
    let dest = Path::new(&out_dir).join("assets_manifest.rs");
    fs::write(&dest, out).unwrap();
    println!("cargo:rerun-if-changed=assets");
    println!("cargo:rerun-if-changed=build.rs");
}

fn walk(root: &Path, dir: &Path, acc: &mut Vec<(String, PathBuf)>) {
    let Ok(rd) = fs::read_dir(dir) else { return };
    for e in rd.flatten() {
        let p = e.path();
        if p.is_dir() {
            walk(root, &p, acc);
        } else if p.extension().map(|e| e == "json").unwrap_or(false) {
            let name = p.strip_prefix(root).unwrap().to_string_lossy().replace('\\', "/");
            acc.push((name, p));
        }
    }
}
